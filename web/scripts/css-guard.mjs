#!/usr/bin/env node
// CSS guard (run by `npm run lint`, hence by `make lint` / `make check`).
// Styling in Arenile = shadcn/ui components + Tailwind utilities on theme
// tokens only (see shared/src/ui/README.md, ADR 0009). This script fails on:
//   1. stylesheets (.css/.scss/.sass/.less/.styl, CSS modules) other than the theme file,
//      anywhere under the scanned apps, public/ included;
//   2. CSS-in-JS libraries and stylesheet imports from TS other than the theme file;
//   3. inline `style={...}` in .tsx, `<style>`/`dangerouslySetInnerHTML`, and
//      `element.style.*` / `cssText` / `setProperty` / `insertRule` in .ts/.tsx/.js;
//   4. Tailwind arbitrary values that bypass the theme: raw colours (`bg-[#…]`,
//      `text-[oklch(…)]`), custom typography (`text-[10px]`, `tracking-[0.3em]`),
//      pixel lengths (`w-[2px]`) and arbitrary properties (`[mask:…]`). Layout
//      values (`h-[65vh]`, `max-w-[32rem]`, `grid-cols-[…]`), `data-[…]` variants,
//      `[&…]` selectors and `w-(--var)` stay allowed;
//   5. `<style>`, `style=""` and stylesheet links in .html files;
//   6. the removed pre-shadcn `--ar-*` tokens (use shadcn tokens instead).
// The only exemptions are the ones listed below, each with its reason. Do not
// add to them without an ADR update.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCAN = ['admin', 'booking', 'shared', 'scripts'];
const SKIP_DIRS = new Set(['node_modules', 'dist', 'dev-dist', 'coverage', 'generated']);

/** The only stylesheet: shadcn theme variables + Tailwind @theme mapping. */
const ALLOWED_STYLESHEETS = ['shared/src/styles/globals.css'];

/** Stylesheets importable from TS/TSX (the theme, imported by each app's main.tsx). */
const ALLOWED_CSS_IMPORTS = ['@arenile/shared/styles/globals.css'];

const CSS_IN_JS = [
  'styled-components',
  '@emotion/',
  'styled-jsx',
  '@stitches/',
  '@vanilla-extract/',
  '@linaria/',
  'linaria',
  'goober',
  'jss',
  'react-jss',
  'aphrodite',
  'twin.macro',
];

/** shadcn components as generated by the CLI (vendored, kept verbatim where possible). */
const VENDORED_RE = /^shared\/src\/ui\/[^/]+\.tsx$/;

/** Inline `style={}` exemptions: SVG geometry that depends on data or measurements. */
const STYLE_ATTR_ALLOW = new Set([
  'shared/src/map/BeachMap.tsx', // caller-provided CSS height of the drawing area
  'shared/src/map/MapLegend.tsx', // establishment colour overrides of the legend swatches
  'admin/src/features/map-editor/MapCanvas.tsx', // zoom factor scales the drawing
]);

/** Programmatic style exemptions (`.style.`, `setProperty`, `<style>`), with their reason. */
const STYLE_CODE_ALLOW = new Set([
  'shared/src/theme/theme.ts', // writes the establishment theme CSS variables (spec 12.5)
  'shared/src/ui/patterns/ThemeProvider.tsx', // `color-scheme` for light/dark on <html>
  'booking/src/embed/embed.ts', // sizes the iframe on the host page, where our CSS does not exist
]);

/** Files allowed to mention `--ar-*` (the test asserting their absence). */
const AR_TOKEN_ALLOW = new Set(['shared/src/theme/theme.test.ts']);

const STYLESHEET_RE = /\.(css|scss|sass|less|styl|pcss)$/i;
const SOURCE_RE = /\.(ts|tsx|js|jsx|mjs)$/;
const HTML_RE = /\.html?$/i;
const IMPORT_RE = /(?:import\s[^'"]*?from\s*|import\s*\(?\s*|require\(\s*)['"]([^'"]+)['"]/g;
const STYLE_ATTR_RE = /\bstyle=\{/g;
const STYLE_CODE_RE =
  /\.style\.[a-zA-Z]|\.cssText\b|\.setProperty\(|\binsertRule\(|<style[\s>]|dangerouslySetInnerHTML|\bstyle:\s*\{/g;
const HTML_STYLE_RE = /<style[\s>]|\sstyle="|rel=["']stylesheet["']/g;

/** Arbitrary values that bypass the theme (message → regex). */
const ARBITRARY = [
  [
    'raw colour (use a theme token: bg-primary, text-muted-foreground…)',
    /-\[(#|rgba?\(|hsla?\(|oklch\(|oklab\(|lab\(|lch\(|color\()/g,
  ],
  [
    'custom typography (use text-xs…text-2xl, tracking-wide…)',
    /\b(?:text|leading|tracking|font)-\[[^\]]*\]/g,
  ],
  ['pixel length (use the spacing scale or a layout unit: rem, vh, %)', /-\[\d+(?:\.\d+)?px\]/g],
  [
    'arbitrary CSS property (use a utility or a component variant)',
    /(?<![&\w-])\[[a-z][a-z-]*:[^\]]*\]/g,
  ],
];

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name) || name.startsWith('.')) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const rel = (file) => relative(ROOT, file).split(sep).join('/');
const lineOf = (text, index) => text.slice(0, index).split('\n').length;

const errors = [];
const fail = (path, text, index, msg) => errors.push(`${path}:${lineOf(text, index)}: ${msg}`);

for (const top of SCAN) {
  let files;
  try {
    files = walk(join(ROOT, top));
  } catch {
    continue;
  }
  for (const file of files) {
    const path = rel(file);
    if (STYLESHEET_RE.test(path)) {
      if (!ALLOWED_STYLESHEETS.includes(path)) {
        errors.push(`${path}: stylesheet not allowed (use shadcn variants + Tailwind utilities)`);
      }
      continue;
    }
    if (HTML_RE.test(path)) {
      const text = readFileSync(file, 'utf8');
      for (const m of text.matchAll(HTML_STYLE_RE)) {
        fail(
          path,
          text,
          m.index,
          `"${m[0].trim()}" not allowed in HTML (the theme is imported by main.tsx)`,
        );
      }
      continue;
    }
    if (!SOURCE_RE.test(path)) continue;
    if (path === 'scripts/css-guard.mjs') continue;
    const text = readFileSync(file, 'utf8');
    const vendored = VENDORED_RE.test(path);

    for (const m of text.matchAll(IMPORT_RE)) {
      const spec = m[1];
      if (
        CSS_IN_JS.some(
          (lib) => spec === lib || spec.startsWith(lib.endsWith('/') ? lib : `${lib}/`),
        )
      ) {
        fail(path, text, m.index, `CSS-in-JS import "${spec}" not allowed`);
      }
      if (STYLESHEET_RE.test(spec.split('?')[0]) && !ALLOWED_CSS_IMPORTS.includes(spec)) {
        fail(path, text, m.index, `stylesheet import "${spec}" not allowed`);
      }
    }

    if (path.endsWith('.tsx') && !vendored && !STYLE_ATTR_ALLOW.has(path)) {
      for (const m of text.matchAll(STYLE_ATTR_RE)) {
        fail(
          path,
          text,
          m.index,
          'inline style={...} not allowed (Tailwind classes; dynamic geometry only in the listed map files)',
        );
      }
    }

    // Tests may read computed styles; the rule targets code that writes them.
    if (!vendored && !STYLE_CODE_ALLOW.has(path) && !/\.test\.[jt]sx?$/.test(path)) {
      for (const m of text.matchAll(STYLE_CODE_RE)) {
        fail(
          path,
          text,
          m.index,
          `"${m[0].trim()}" not allowed (no programmatic CSS; see the exemptions in css-guard.mjs)`,
        );
      }
    }

    if (!vendored) {
      for (const [msg, re] of ARBITRARY) {
        for (const m of text.matchAll(re)) {
          fail(path, text, m.index, `Tailwind arbitrary value "${m[0]}": ${msg}`);
        }
      }
    }

    if (text.includes('--ar-') && !AR_TOKEN_ALLOW.has(path)) {
      fail(
        path,
        text,
        text.indexOf('--ar-'),
        'removed --ar-* token (use shadcn tokens: bg-primary, text-primary-on-surface, rounded-lg...)',
      );
    }
  }
}

if (errors.length > 0) {
  console.error('css-guard: styling rules violated (see web/shared/src/ui/README.md):');
  for (const e of errors) console.error(`  ${e}`);
  process.exit(1);
}
console.log('css-guard: ok');
