#!/usr/bin/env node
// CSS guard (run by `npm run lint`, hence by `make lint` / `make check`).
// Styling in Arenile = shadcn/ui components + Tailwind utilities only
// (see shared/src/ui/README.md). This script fails on:
//   1. stylesheets (.css/.scss/.sass/.less/.styl, CSS modules) other than the theme file;
//   2. CSS-in-JS libraries and stylesheet imports from TS other than the theme file;
//   3. inline `style={...}` in .tsx outside the allowlist (dynamic map geometry,
//      vendored shadcn components);
//   4. the removed pre-shadcn `--ar-*` tokens (use shadcn tokens instead).
// There are no exceptions lists: never add one.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCAN = ['admin', 'booking', 'shared', 'scripts'];
const SKIP_DIRS = new Set(['node_modules', 'dist', 'dev-dist', 'coverage', 'generated', 'public']);

/** The only stylesheet: shadcn theme variables + Tailwind @theme mapping. */
const ALLOWED_STYLESHEETS = ['shared/src/styles/globals.css'];

/** Stylesheets importable from TS/TSX (the theme, imported by each app's main.tsx). */
const ALLOWED_CSS_IMPORTS = ['@arenile/shared/styles/globals.css'];

const CSS_IN_JS = [
  'styled-components',
  '@emotion/',
  'styled-jsx',
  '@stitches/',
  '@vanilla-extract/',
  '@linaria/',
  'linaria',
  'goober',
  'jss',
  'react-jss',
  'aphrodite',
  'twin.macro',
];

/** Inline style allowed: dynamic geometry and vendored shadcn components. */
const STYLE_ALLOW = [
  /^shared\/src\/map\//, // SVG map renderer (measured heights, override colours)
  /^admin\/src\/features\/map-editor\//, // map editor canvas geometry
  /^shared\/src\/ui\/[^/]+\.tsx$/, // shadcn components as generated by the CLI
];

/** Files allowed to mention `--ar-*` (the guard itself and the test asserting their absence). */
const AR_TOKEN_ALLOW = ['shared/src/theme/theme.test.ts'];

const STYLESHEET_RE = /\.(css|scss|sass|less|styl|pcss)$/i;
const SOURCE_RE = /\.(ts|tsx|js|jsx|mjs)$/;
const IMPORT_RE = /(?:import\s[^'"]*?from\s*|import\s*\(?\s*|require\(\s*)['"]([^'"]+)['"]/g;
const STYLE_ATTR_RE = /\bstyle=\{/g;

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name) || name.startsWith('.')) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const rel = (file) => relative(ROOT, file).split(sep).join('/');
const lineOf = (text, index) => text.slice(0, index).split('\n').length;

const errors = [];

for (const top of SCAN) {
  let files;
  try {
    files = walk(join(ROOT, top));
  } catch {
    continue;
  }
  for (const file of files) {
    const path = rel(file);
    if (STYLESHEET_RE.test(path)) {
      if (!ALLOWED_STYLESHEETS.includes(path)) {
        errors.push(`${path}: stylesheet not allowed (use shadcn variants + Tailwind utilities)`);
      }
      continue;
    }
    if (!SOURCE_RE.test(path)) continue;
    const text = readFileSync(file, 'utf8');
    if (path === 'scripts/css-guard.mjs') continue;

    for (const m of text.matchAll(IMPORT_RE)) {
      const spec = m[1];
      if (
        CSS_IN_JS.some(
          (lib) => spec === lib || spec.startsWith(lib.endsWith('/') ? lib : `${lib}/`),
        )
      ) {
        errors.push(`${path}:${lineOf(text, m.index)}: CSS-in-JS import "${spec}" not allowed`);
      }
      if (STYLESHEET_RE.test(spec.split('?')[0]) && !ALLOWED_CSS_IMPORTS.includes(spec)) {
        errors.push(`${path}:${lineOf(text, m.index)}: stylesheet import "${spec}" not allowed`);
      }
    }

    if (path.endsWith('.tsx') && !STYLE_ALLOW.some((re) => re.test(path))) {
      const hits = [...text.matchAll(STYLE_ATTR_RE)];
      for (const h of hits)
        errors.push(
          `${path}:${lineOf(text, h.index)}: inline style={...} not allowed (Tailwind classes; dynamic geometry only in allowlisted map files)`,
        );
    }

    if (text.includes('--ar-') && !AR_TOKEN_ALLOW.includes(path)) {
      errors.push(
        `${path}:${lineOf(text, text.indexOf('--ar-'))}: removed --ar-* token (use shadcn tokens: bg-primary, text-primary-on-surface, rounded-lg...)`,
      );
    }
  }
}

if (errors.length > 0) {
  console.error('css-guard: styling rules violated (see web/shared/src/ui/README.md):');
  for (const e of errors) console.error(`  ${e}`);
  process.exit(1);
}
console.log('css-guard: ok');
